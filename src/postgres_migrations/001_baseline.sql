
-- 001_baseline.sql
-- Complete PostgreSQL schema corresponding to SQLite migrations 001-005.
-- Existing SQLite migrations remain unchanged.

CREATE TABLE vendors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_name TEXT NOT NULL UNIQUE,
    is_approved BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TEXT NOT NULL
);

CREATE TABLE purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id BIGINT NOT NULL REFERENCES vendors(id),
    po_number TEXT NOT NULL,
    po_amount DOUBLE PRECISION NOT NULL,
    currency TEXT NOT NULL DEFAULT 'INR',
    created_at TEXT NOT NULL,
    UNIQUE (vendor_id, po_number)
);

CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id BIGINT NOT NULL REFERENCES vendors(id),
    invoice_number TEXT NOT NULL,
    invoice_date TEXT NOT NULL,
    due_date TEXT,
    currency TEXT NOT NULL,
    total DOUBLE PRECISION NOT NULL,
    po_number TEXT,
    extracted_data TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'received',
    created_at TEXT NOT NULL,
    thread_id TEXT,
    UNIQUE (vendor_id, invoice_number)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT REFERENCES invoices(id),
    action TEXT NOT NULL,
    actor TEXT NOT NULL,
    details TEXT,
    created_at TEXT NOT NULL
);

CREATE TABLE invoice_review_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number TEXT NOT NULL,
    vendor_name TEXT NOT NULL,
    case_type TEXT NOT NULL,
    invoice_data TEXT NOT NULL,
    validation_report TEXT NOT NULL,
    risk_level TEXT NOT NULL,
    existing_invoice_id BIGINT REFERENCES invoices(id),
    status TEXT NOT NULL DEFAULT 'open',
    reviewer_reason TEXT,
    created_at TEXT NOT NULL,
    reviewed_at TEXT,
    CHECK (case_type IN ('unknown_vendor', 'duplicate')),
    CHECK (status IN ('open', 'rejected', 'resolved'))
);

CREATE TABLE submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id TEXT NOT NULL UNIQUE,
    sha256 TEXT NOT NULL,
    filename TEXT NOT NULL,
    mime TEXT,
    stored_path TEXT,
    submitted_by TEXT,
    status TEXT NOT NULL DEFAULT 'queued',
    attempts INTEGER NOT NULL DEFAULT 0,
    error TEXT,
    resubmission_of BIGINT REFERENCES submissions(id),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    CHECK (
        status IN (
            'queued',
            'processing',
            'awaiting_approval',
            'completed',
            'failed',
            'review_case'
        )
    )
);

CREATE TABLE llm_calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id TEXT,
    step TEXT NOT NULL,
    provider TEXT NOT NULL,
    model TEXT NOT NULL,
    attempt INTEGER NOT NULL DEFAULT 1,
    outcome TEXT NOT NULL,
    error_type TEXT,
    error_category TEXT,
    prompt_tokens INTEGER,
    output_tokens INTEGER,
    thinking_tokens INTEGER,
    total_tokens INTEGER,
    latency_ms INTEGER,
    est_cost_usd DOUBLE PRECISION,
    pricing_version TEXT,
    started_at TEXT NOT NULL,
    created_at TEXT NOT NULL,
    CHECK (attempt >= 1),
    CHECK (
        outcome IN (
            'success',
            'retryable_error',
            'error',
            'invalid_response'
        )
    ),
    CHECK (prompt_tokens IS NULL OR prompt_tokens >= 0),
    CHECK (output_tokens IS NULL OR output_tokens >= 0),
    CHECK (thinking_tokens IS NULL OR thinking_tokens >= 0),
    CHECK (total_tokens IS NULL OR total_tokens >= 0),
    CHECK (latency_ms IS NULL OR latency_ms >= 0),
    CHECK (est_cost_usd IS NULL OR est_cost_usd >= 0)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TEXT,
    last_login_at TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    CHECK (
        role IN (
            'admin',
            'finance_manager',
            'reviewer',
            'uploader'
        )
    ),
    CHECK (failed_attempts >= 0)
);

-- Invoice indexes
CREATE INDEX idx_invoice_number
    ON invoices(invoice_number);

CREATE INDEX idx_invoice_status
    ON invoices(status);

CREATE UNIQUE INDEX idx_invoices_thread_id
    ON invoices(thread_id)
    WHERE thread_id IS NOT NULL;

-- Purchase order index
CREATE INDEX idx_po_number
    ON purchase_orders(po_number);

-- Review case index
CREATE INDEX idx_review_case_status
    ON invoice_review_cases(status);

-- Submission indexes
CREATE INDEX idx_submissions_sha256
    ON submissions(sha256);

CREATE INDEX idx_submissions_status
    ON submissions(status);

-- LLM telemetry indexes
CREATE INDEX idx_llm_calls_thread_id
    ON llm_calls(thread_id);

CREATE INDEX idx_llm_calls_created_at
    ON llm_calls(created_at);

-- Case-insensitive username uniqueness (SQLite NOCASE equivalent)
CREATE UNIQUE INDEX idx_users_username_lower
    ON users(LOWER(username));
