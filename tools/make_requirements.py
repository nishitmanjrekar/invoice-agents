import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

BACKEND = [
    "fastapi", "uvicorn", "python-multipart", "pydantic", "langgraph",
    "langgraph-checkpoint-sqlite", "google-genai", "python-dotenv", "mcp", "PyJWT", "SQLAlchemy", "psycopg", "langgraph-checkpoint-postgres", "boto3",
]
FRONTEND = ["streamlit", "pandas", "plotly", "requests"]
DEV = ["pytest", "ruff", "httpx"]

HEADER = "# Generated by tools/make_requirements.py from the installed environment.\n"


def pins(names):
    lines, missing = [], []
    for name in names:
        try:
            lines.append(f"{name}=={metadata.version(name)}")
        except metadata.PackageNotFoundError:
            missing.append(name)
    return lines, missing


def main():
    outputs = {
        "requirements.txt": (BACKEND, []),
        "requirements-frontend.txt": (FRONTEND, []),
        "requirements-dev.txt": (DEV, ["-r requirements.txt"]),
    }
    rendered, all_missing = {}, []
    for filename, (names, prefix) in outputs.items():
        lines, missing = pins(names)
        all_missing += missing
        rendered[filename] = HEADER + "\n".join(prefix + lines) + "\n"

    if all_missing:
        print("Not installed, nothing written:", ", ".join(all_missing))
        sys.exit(1)

    for filename, content in rendered.items():
        (ROOT / filename).write_text(content, encoding="utf-8")
        print(f"--- {filename}\n{content}")


if __name__ == "__main__":
    main()